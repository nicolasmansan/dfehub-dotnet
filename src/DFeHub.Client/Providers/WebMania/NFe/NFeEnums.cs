namespace DFeHub.Providers.WebMania.NFe;

/// <summary>
/// Identifies the SEFAZ environment.
/// </summary>
public enum NFeEnvironment
{
    /// <summary>
    /// Production environment.
    /// </summary>
    Production = 1,

    /// <summary>
    /// Certification environment without fiscal value.
    /// </summary>
    Certification = 2,
}

/// <summary>
/// Identifies whether a document records an inbound or outbound operation.
/// </summary>
public enum NFeOperation
{
    /// <summary>
    /// Inbound operation.
    /// </summary>
    Inbound = 0,

    /// <summary>
    /// Outbound operation.
    /// </summary>
    Outbound = 1,
}

/// <summary>
/// Identifies the invoice model accepted by the API 1.0 endpoint.
/// </summary>
public enum NFeModel
{
    /// <summary>
    /// NF-e.
    /// </summary>
    NFe = 1,

    /// <summary>
    /// NFC-e.
    /// </summary>
    NFCe = 2,
}

/// <summary>
/// Identifies the fiscal purpose of an issuance request.
/// </summary>
public enum NFePurpose
{
    /// <summary>
    /// Normal invoice.
    /// </summary>
    Normal = 1,

    /// <summary>
    /// Adjustment or reversal.
    /// </summary>
    Adjustment = 3,

    /// <summary>
    /// Return.
    /// </summary>
    Return = 4,

    /// <summary>
    /// Credit note.
    /// </summary>
    Credit = 5,

    /// <summary>
    /// Debit note.
    /// </summary>
    Debit = 6,
}

/// <summary>
/// Identifies the recipient manifestation event.
/// </summary>
public enum NFeRecipientManifestation
{
    /// <summary>
